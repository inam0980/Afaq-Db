@register.filter
def initials(name) -> str:
    """'Ahmed Khan' -> 'AK'; first letter of the first and last word."""
    words = (name or "").split()
    if not words:
        return "?"
    letters = words[0][0] + (words[-1][0] if len(words) > 1 else "")
    return letters.upper()


@register.simple_tag
def icon(name: str, size: int = 18):
    try:
        body = ICONS[name]
    except KeyError:
        raise ValueError(f"Unknown icon {name!r}") from None
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" width="{0}" height="{0}" viewBox="0 0 24 24" '
        'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" '
        'stroke-linejoin="round" class="icon" aria-hidden="true">{1}</svg>',
        size,
        mark_safe(body),  # trusted constant above
    )


SOON_DAYS = 30


@register.filter
def days_left(date):
    """Days from today (Riyadh) until `date`; negative if already past."""
    if date is None:
        return None
    from django.utils import timezone

    return (date - timezone.localdate()).days


@register.filter
def expiry_tone(date) -> str:
    """'expired' | 'soon' (within 30 days) | 'ok' | 'none' (no date)."""
    left = days_left(date)
    if left is None:
        return "none"
    if left < 0:
        return "expired"
    if left <= SOON_DAYS:
        return "soon"
    return "ok"


@register.filter
def absolute(value):
    return abs(value)


@functools.lru_cache(maxsize=64)
def _file_version(full_path: str, mtime: float) -> str:
    with open(full_path, "rb") as fh:
        return hashlib.md5(fh.read(), usedforsecurity=False).hexdigest()[:10]


@register.simple_tag
def asset(path: str) -> str:
    """Static URL with a content hash (?v=...) so browsers never serve a
    stale stylesheet after an update. Re-hashes only when the file changes."""
    url = static(path)
    full_path = finders.find(path)
    if not full_path:
        return url
    return f"{url}?v={_file_version(full_path, os.path.getmtime(full_path))}"
