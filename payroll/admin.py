from django.contrib import admin
from django.contrib.admin.options import ActionLocation
from simple_history.admin import SimpleHistoryAdmin

from payroll.models import GosiRate, PayrollRun, Payslip, SalaryStructure


@admin.register(SalaryStructure)
class SalaryStructureAdmin(SimpleHistoryAdmin):
    list_display = ["employee", "effective_from", "basic", "housing", "transport", "other"]
    list_filter = ["effective_from"]
    search_fields = ["employee__employee_no", "employee__first_name", "employee__last_name"]
    autocomplete_fields = ["employee"]
    list_select_related = ["employee"]
    date_hierarchy = "effective_from"


@admin.register(GosiRate)
class GosiRateAdmin(SimpleHistoryAdmin):
    list_display = ["category", "effective_from", "employee_rate", "employer_rate", "salary_cap"]
    list_filter = ["category"]


class _NoBulkDeleteMixin:
    """Bulk delete uses queryset.delete(), which bypasses the payroll lock."""

    def get_actions(self, request, action_location=ActionLocation.CHANGE_LIST):
        actions = super().get_actions(request, action_location=action_location)
        actions.pop("delete_selected", None)
        return actions


@admin.register(PayrollRun)
class PayrollRunAdmin(_NoBulkDeleteMixin, SimpleHistoryAdmin):
    list_display = ["__str__", "status", "created_by", "approved_by", "approved_at", "paid_at"]
    list_filter = ["status", "year"]
    readonly_fields = ["status", "created_by", "created_at", "approved_by", "approved_at", "paid_at"]

    def has_delete_permission(self, request, obj=None):
        if obj is not None and obj.is_locked:
            return False
        return super().has_delete_permission(request, obj)


@admin.register(Payslip)
class PayslipAdmin(_NoBulkDeleteMixin, SimpleHistoryAdmin):
    list_display = ["run", "employee", "gross", "total_deductions", "net"]
    list_filter = ["run"]
    search_fields = ["employee__employee_no", "employee__first_name", "employee__last_name"]
    list_select_related = ["run", "employee"]

    def has_add_permission(self, request):
        return False   # payslips are generated by the payroll run

    def has_change_permission(self, request, obj=None):
        return False   # inputs are edited on the payroll run page

    def has_delete_permission(self, request, obj=None):
        return False
